cL = 1
function onCreate()
    setProperty('camHUD'..'.flashSprite.scaleX', 2)
        setProperty('camHUD'..'.flashSprite.scaleY', 2)
        runHaxeCode("game."..'camHUD'..".setScale(game."..'camHUD'..".zoom / 2, game."..'camHUD'..".zoom / 2);")
    makeLuaText('captions', '...', 1280, 0, 500)
    setTextSize('captions', 30)
    setObjectCamera('captions', 'other')
    setTextAlignment('captions', 'center')
    addLuaText('captions')
end
function onEvent(n,v1,v2)
    if n == '' then
        if v1 == 'lyric' then
            if cL <= #lyric then
                setTextString('captions', lyric[cL])
                setTextSize('captions', 30)
                setTextColor('captions', 'white')
                setProperty('captions.alpha', 1)
                if cL == #lyric or cL == 45 or cL == 92 or cL == 103 or cL == 122 or cL == 174 or cL == 235 or cL == 246 or cL == 265 or cL == 317 then
                    doTweenAlpha('hide', 'captions', 0, 1)
                elseif cL == 128 or cL == 151 or cL == 188 or cL == 271 or cL == 294 or cL == 331 or cL == 346 then
                    setTextSize('captions', 40)
                elseif cL == 129 or cL == 152 or cL == 189 or cL == 272 or cL == 295 or cL == 332 or cL == 347 then
                    setTextSize('captions', 50)
                    setTextColor('captions', 'red')
                end
                cL = cL+1
            end
        end
        v2 = tonumber(v2)
        if v1 == 'i' then
            eVentedI = true
            zoomThing()
        elseif v1 == 'o' then
            eVentedO = true
            zoomThing()
        elseif v1 == 't' then
            eVentedT = true
            zoomThing()
        end
    end
end
local zoomies = false
function onBeatHit()
    if curBeat == 113 or curBeat == 225 then
        rotAte = true
    elseif curBeat == 161 or curBeat == 289 then
        rotAte = false
        doTweenAngle('hudangle', 'camHUD', 0, 0.8, 'expoOut')
    end
    if zoomies then
        setProperty('camHUD.zoom', 0.55)
        doTweenZoom('hudzoom', 'camHUD', 0.5, 0.4, 'expoIn')
    end
    if rotAte and not rR and (curBeat % 4 == 1 or curBeat % 4 == 3) then
        doTweenAngle('hudangle', 'camHUD', 25, 0.8, 'expoOut')
        rR = true
    elseif rotAte and rR and (curBeat % 4 == 1 or curBeat % 4 == 3) then
        doTweenAngle('hudangle', 'camHUD', -25, 0.8, 'expoOut')
        rR = false
    end
end
