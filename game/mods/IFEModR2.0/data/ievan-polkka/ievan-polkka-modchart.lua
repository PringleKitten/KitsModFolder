function onEvent(n,v1,v2)
    v2 = tonumber(v2) or 1
    if v1 == 'lyric' then
        if cL <= #lyric then
            setTextString('captions', lyric[cL])
            setTextSize('captions', 30)
            setTextColor('captions', 'white')
            setProperty('captions.alpha', 1)
            if cL == 86 or cL == 205 then
                doTweenAlpha('hide', 'captions', 0, 0.44, 'sineOut')
            elseif cL == #lyric or cL == 205 then
                doTweenAlpha('hide', 'captions', 0, 3, 'sineOut')
            end
            cL = cL+1
        end
    end
    if n == '' then
        if v1 == 'zi' then
            setProperty('defaultCamZoom', getProperty('defaultCamZoom')+(0.2*v2))
        end
        if v1 == 'zo' then
            setProperty('defaultCamZoom', getProperty('defaultCamZoom')-(0.2*v2))
        end
        if v1 == 'click' then
            if not click then
                click = true
            else
                click = false
            end
        end
        if v1 == 'click2' then
            mydefaultPlayerStrumX0 = getPropertyFromGroup('playerStrums', 0, 'x')
            mydefaultPlayerStrumX1 = getPropertyFromGroup('playerStrums', 1, 'x')
            mydefaultPlayerStrumX2 = getPropertyFromGroup('playerStrums', 2, 'x')
            mydefaultPlayerStrumX3 = getPropertyFromGroup('playerStrums', 3, 'x')
            mydefaultPlayerStrumY0 = getPropertyFromGroup('playerStrums', 0, 'y')
            mydefaultPlayerStrumY1 = getPropertyFromGroup('playerStrums', 1, 'y')
            mydefaultPlayerStrumY2 = getPropertyFromGroup('playerStrums', 2, 'y')
            mydefaultPlayerStrumY3 = getPropertyFromGroup('playerStrums', 3, 'y')
            if not click2 then
                click2 = true
            else
                click2 = false
            end
        end
    end
end
