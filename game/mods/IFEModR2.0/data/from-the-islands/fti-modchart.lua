cL = 1
function onSongStart()
	makeLuaSprite('vignette', 'me/popup/vignettepgk', 0, 0)
	scaleObject('vignette', 4, 4)
	setObjectCamera('vignette', 'hud')
	setProperty('vignette.alpha', 1)
	addLuaSprite('vignette', true)
	local origFollowX = getProperty('camFollow.x')
	local origFollowY = getProperty('camFollow.y')
	local origZoom = getProperty('camGame.zoom')
	setProperty('camFollow.x', origFollowX - 500)
	setProperty('camFollow.y', origFollowY + 250)
	setProperty('camGame.zoom', origZoom * 2.5)
	setProperty('isCameraOnForcedPos', true)
	doTweenAlpha('vignetteOut', 'vignette', 0, 9.35, 'linear')
	doTweenX('camFollowX', 'camFollow', origFollowX, 9.35, 'sineIn')
	doTweenY('camFollowY', 'camFollow', origFollowY, 9.35, 'sineIn')
	doTweenZoom('cameraZoom', 'camGame', origZoom, 9.35, 'sineIn')
end
function onCreate()
	makeLuaText('captions', '...', 1280, 0, 500)
    setTextSize('captions', 30)
    setObjectCamera('captions', 'other')
    setTextAlignment('captions', 'center')
    addLuaText('captions')
end
function onUpdate()
	if curStep <= 64 then
		setProperty('defaultCamZoom', getProperty('camGame.zoom'))
	end
end
function onEvent(e, v1, v2)
	if e == '' then
		if v1 == 'lyric' then
    	    if cL <= #lyric then
    	        setTextString('captions', lyric[cL])
    	        setTextSize('captions', 30)
    	        setTextColor('captions', 'white')
    	        setProperty('captions.alpha', 1)
    	        if cL == 56 or cL == 64 or cL == 73 or cL == 121 or cL == 177 or cL == 186 or cL == 267 or cL == 273 or cL == 283 or cL == 285 or cL == 340 or cL == 345 then
    	            doTweenAlpha('hide', 'captions', 0, 0.5, 'sineOut')
    	        elseif cL == #lyric then
    	            doTweenAlpha('hide', 'captions', 0, 3, 'sineOut')
    	        end
    	        cL = cL+1
    	    end
    	end
		if v1 == 'sg' then
            local vt = {}
            for value in string.gmatch(v2, '([^,]+)') do
                local number = load("return " .. value)()
                table.insert(vt, number)
            end
            if vt[1] and vt[2] and vt[3] then
				vt[3] = tostring(vt[3])
                doTweenZoom('zoomCS', 'camGame', getProperty('camGame.zoom')+vt[1], vt[2], vt[3])
            end
        end
	end
end

function onStepHit()
	if curStep == 62 then
		doTweenZoom('zoomIn', 'camGame', getProperty('camGame.zoom') + 0.5, 0.15, 'sineOut')
	elseif curStep == 63 then
		doTweenZoom('zoomOut', 'camGame', getProperty('camGame.zoom') - 0.5, 0.15, 'sineIn')
	elseif curStep == 64 then
		cancelTween('camFollowX')
		cancelTween('camFollowY')
		cancelTween('cameraZoom')
		setProperty('isCameraOnForcedPos', false)
	end
end

function onTweenCompleted(t)
	if t == 'zoomCS' then
		setProperty('defaultCamZoom', getProperty('camGame.zoom'))
	end
end